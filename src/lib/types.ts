// Option lists are the single source of truth for both the forms and the DB CHECK constraints.
export const AREAS = ['Anand', 'VV Nagar', 'Karamsad', 'Bakrol', 'Mogri', 'Nadiad', 'Other'] as const;
export const SOFA_SIZES = ['3 Seater', '4 Seater', '5 Seater', '6 Seater', '7 Seater', 'L-Shape', 'Other'] as const;
export const BOOKING_STATUSES = ['New', 'Confirmed', 'In Progress', 'Completed', 'Cancelled'] as const;
export const TIME_SLOTS = ['Morning (9am–12pm)', 'Afternoon (12pm–4pm)', 'Evening (4pm–7pm)', 'Flexible'] as const;
export const PAYMENT_METHODS = ['Cash', 'UPI', 'Bank Transfer'] as const;
export const PAYMENT_STATUSES = ['Paid', 'Unpaid'] as const;
export const EXPENSE_CATEGORIES = ['Meta Ads', 'Fuel', 'Chemicals', 'Equipment', 'Other'] as const;
export const PAID_BY = ['Founder 1', 'Founder 2', 'Business'] as const;
export const SERVICE_NAME = 'Sofa deep cleaning';

export type Area = (typeof AREAS)[number];
export type SofaSize = (typeof SOFA_SIZES)[number];
export type BookingStatus = (typeof BOOKING_STATUSES)[number];
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];
export type PaymentStatus = (typeof PAYMENT_STATUSES)[number];
export type ExpenseCategory = (typeof EXPENSE_CATEGORIES)[number];
export type PaidBy = (typeof PAID_BY)[number];

export interface Booking {
  id: string;
  customer_name: string;
  phone: string;
  area: Area;
  address: string;
  sofa_size: SofaSize;
  service: string;
  booking_date: string; // YYYY-MM-DD
  preferred_time: string;
  price: number;
  notes: string | null;
  status: BookingStatus;
}
export type BookingInput = Omit<Booking, 'id'>;

export interface Payment {
  id: string;
  booking_id: string;
  amount: number;
  method: PaymentMethod;
  payment_date: string;
  status: PaymentStatus;
}
export type PaymentInput = Omit<Payment, 'id'>;

export interface Expense {
  id: string;
  expense_date: string;
  category: ExpenseCategory;
  amount: number;
  paid_by: PaidBy;
  notes: string | null;
  is_capital_asset: boolean; // generated by the database from category = 'Equipment'
}
export type ExpenseInput = Omit<Expense, 'id' | 'is_capital_asset'>;

export interface OpeningBalance {
  id: string;
  label: string;
  category: ExpenseCategory | null;
  kind: 'jobs' | 'revenue' | 'expense' | 'asset';
  amount: number;
  note: string | null;
}

export interface BusinessData {
  bookings: Booking[];
  payments: Payment[];
  expenses: Expense[];
  openingBalances: OpeningBalance[];
}
